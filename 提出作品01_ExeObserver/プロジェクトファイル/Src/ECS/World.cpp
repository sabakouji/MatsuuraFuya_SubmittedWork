#include "World.h"
#include <algorithm>

//-----------------------------------------------------------------------------
// シングルトンインスタンス取得
World& World::GetInstance()
{
    static World instance;
    return instance;
}
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// エンティティを生成
EntityID World::CreateEntity()
{
    EntityID id = nextId_++;
    alive_.insert(id);
    return id;
}
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// エンティティを破棄キューに追加
void World::DestroyEntity(EntityID id)
{
    destroyQueue_.push_back(id);
}
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// 破棄キューを実際に削除する（Updateの冒頭で呼ぶ）
void World::FlushDestroyQueue()
{
    for (EntityID id : destroyQueue_)
    {
        if (!IsAlive(id)) continue;

        // 保有する全コンポーネントを削除（活性: パーティクル＋弾＋敵ボディ）
        particles_.Remove(id);
        bullets_.Remove(id);
        enemyBodies_.Remove(id);

        alive_.erase(id);
    }
    destroyQueue_.clear();
}
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// エンティティが有効か確認
bool World::IsAlive(EntityID id) const
{
    return alive_.find(id) != alive_.end();
}
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// Systemを登録
void World::RegisterSystem(std::unique_ptr<ISystem> system)
{
    systems_.push_back(std::move(system));
}
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// 登録済みSystemを順次実行
void World::UpdateSystems()
{
    FlushDestroyQueue();
    for (auto& system : systems_)
    {
        system->Update();
    }
}
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// 全エンティティ・コンポーネント・Systemをリセット
void World::Clear()
{
    particles_.Clear();
    bullets_.Clear();
    enemyBodies_.Clear();

    alive_.clear();
    destroyQueue_.clear();
    systems_.clear();
    nextId_ = 0;
}
//-----------------------------------------------------------------------------