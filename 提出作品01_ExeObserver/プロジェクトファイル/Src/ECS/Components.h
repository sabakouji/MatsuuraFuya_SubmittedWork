#pragma once
//=============================================================================
// ECS - コンポーネント定義
//   コンポーネントは純粋なデータ構造体（メソッドなし）
//   ロジックはすべてSystemに集約する
//   ※案B: ECSで活性なのはパーティクルのみ。敵・弾等のコンポーネントは整理済み。
//=============================================================================
#include "../MyMath.h"

//=============================================================================
// パーティクルコンポーネント（Effect ECS化用）
//=============================================================================
struct ParticleComponent
{
    VECTOR3 position  = {0.0f, 0.0f, 0.0f};
    VECTOR3 velocity  = {0.0f, 0.0f, 0.0f};
    VECTOR3 color     = {1.0f, 1.0f, 1.0f};
    float   alpha     = 1.0f;
    float   size      = 1.0f;
    float   lifetime  = 1.0f;   // 残り寿命（秒）
    float   maxLife   = 1.0f;   // 初期寿命（正規化用）
    int     texId     = 0;      // テクスチャID
    bool    alive     = false;  // プール内の有効フラグ
};

//=============================================================================
// 弾コンポーネント（Bullet ECS化用）
//   旧 OOP WeaponBullet の状態をデータ化。ロジックは BulletSystem に集約する。
//=============================================================================
struct BulletComponent
{
    VECTOR3 position     = {0.0f, 0.0f, 0.0f};
    VECTOR3 velocity     = {0.0f, 0.0f, 0.0f};  // 進行方向×速度（秒速・発射時に確定）
    VECTOR3 rotation     = {0.0f, 0.0f, 0.0f};  // 描画向き（オイラー角・発射時に確定）
    int     owner        = 0;                    // 所有者区分（WeaponBase::OwnerID: ePC/eENM）
    float   lifeDistance = 50.0f;                // 残り生存距離（0で消滅）
    bool    alive        = false;                // プール内の有効フラグ
};

//=============================================================================
// 敵ボディコンポーネント（Enemy ECS化・段階的ハイブリッド用）
//   OOP の transform.position を正本とし、本コンポーネントは物理データをミラーする。
//   System は押し戻し量(pushOut)等を「出力」として算出し、OOP がそれを適用する。
//   ※FSM思考・アニメ・FBX描画には関与しない（OOP維持）。
//=============================================================================
struct EnemyBodyComponent
{
    VECTOR3 position = {0.0f, 0.0f, 0.0f};  // 入力: 毎フレーム OOP から同期される現在位置
    float   radius   = 1.5f;                // 入力: 押し合い用の球半径
    VECTOR3 pushOut  = {0.0f, 0.0f, 0.0f};  // 出力: System が算出する押し戻し量（OOPが適用）
    float   speedY   = 0.0f;                // 落下速度（EnemyPhysicsSystemが重力積分・接地でOOPが0クリア）
    bool    alive    = false;               // プール内の有効フラグ
};